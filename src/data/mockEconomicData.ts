// Helper to generate 10-year Quarterly series (40 quarters: 2016-Q4 to 2026-Q3)
function buildQuarterlySeries(
  values: { year: number; q: 1 | 2 | 3 | 4; val: number; sec?: number; tert?: number; note?: string }[]
): ObservationPoint[] {
  return values.map((item, idx) => {
    const month = item.q * 3;
    const timestamp = new Date(item.year, month - 1, 15).getTime();
    const status = idx >= values.length - 2 ? 'Provisional' : idx >= values.length - 4 ? 'Revised' : 'Final';
    return {
      date: `${item.year}-Q${item.q}`,
      timestamp,
      label: `Q${item.q} ${item.year}`,
      value: item.val,
      secondaryValue: item.sec,
      tertiaryValue: item.tert,
      status,
      note: item.note,
    };
  });
}

// Helper to generate 10-year Monthly checkpoints (every 3 months from 2016 to 2024 + monthly for 2025-2026)
function buildMonthlyTenYearSeries(
  points: { ym: string; val: number; sec?: number; tert?: number; note?: string }[]
): ObservationPoint[] {
  const monthNames = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  return points.map((pt, idx) => {
    const [yStr, mStr] = pt.ym.split('-');
    const year = parseInt(yStr, 10);
    const month = parseInt(mStr, 10);
    const timestamp = new Date(year, month - 1, 15).getTime();
    const status = idx >= points.length - 2 ? 'Provisional' : 'Final';
    return {
      date: pt.ym,
      timestamp,
      label: `${monthNames[month - 1]} ${year}`,
      value: pt.val,
      secondaryValue: pt.sec,
      tertiaryValue: pt.tert,
      status,
      note: pt.note,
    };
  });
}

